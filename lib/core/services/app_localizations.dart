/// Centralized localization service for MotoPOS.
///
/// Call [init] once in `main()` before `runApp()`.
/// Then use [get] anywhere: `AppLocalizations.get('key')`.
class AppLocalizations {
  static String _currentLang = 'en';

  static String get currentLang => _currentLang;

  /// Load saved language from SharedPreferences.
  static Future<void> init() async {
    final prefs = await SharedPreferences.getInstance();
    _currentLang = prefs.getString('app_language') ?? 'en';
  }

  /// Resolve a translation key. Returns the key itself if not found.
  static String get(String key) {
    final map = _currentLang == 'id' ? _id : _en;
    return map[key] ?? _en[key] ?? key;
  }

